# Compiles check_samples.comp.glsl into check_samples.hpp. Needs glslc from the Vulkan SDK; run it after changing the
# shader: python generate.py
import os
import pathlib
import subprocess
import tempfile

directory = pathlib.Path(__file__).parent
glslc = pathlib.Path(os.environ.get("VULKAN_SDK", "")) / "Bin" / "glslc"

with tempfile.TemporaryDirectory() as temporary:
    output = pathlib.Path(temporary) / "check_samples.spv"
    subprocess.run([str(glslc), "-fshader-stage=comp", "-O", str(directory / "check_samples.comp.glsl"), "-o", str(output)],
                   check=True)
    data = output.read_bytes()

words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
body = ", ".join(f"0x{word:08x}" for word in words)
lines = [
    "#pragma once",
    "",
    "// Generated by generate.py from check_samples.comp.glsl. Do not edit.",
    "",
    "#include <array>",
    "#include <cstdint>",
    "",
    "// clang-format off",
    f"inline constexpr std::array<uint32_t, {len(words)}> check_samples_shader{{{body}}};",
    "// clang-format on",
    "",
]
(directory / "check_samples.hpp").write_text("\n".join(lines), newline="\n")
