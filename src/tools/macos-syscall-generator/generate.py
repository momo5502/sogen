#!/usr/bin/env python3
"""Generate the macOS BSD syscall numbers and names from XNU's bsd/kern/syscalls.master.

The macOS emulator dispatches BSD syscalls by number and names them in its logs. Both come from
syscalls.master of the XNU release the emulation root was built from; its Libsyscall version in the
shared cache ("PROJECT:Libsyscall-<version>") is that XNU version. The master file itself is not
checked in.

This runs offline; the generated header is checked in. Regenerate it after moving to another XNU
release:

    curl -O https://raw.githubusercontent.com/apple-oss-distributions/xnu/xnu-<version>/bsd/kern/syscalls.master
    python3 src/tools/macos-syscall-generator/generate.py --syscalls-master syscalls.master \\
        --xnu-version xnu-<version> --output src/macos-emulator/macos_syscall_numbers.generated.hxx
"""

import argparse
import re
import sys

ENTRY = re.compile(r"^(\d+)\s+\S+\s+\S+\s+\{([^}]*)\}")
FUNCTION_NAME = re.compile(r"(\w+)\s*\(")

# Numbers without a syscall of their own: the indirect syscall, retired calls and configurations
# compiled out.
UNUSED_FUNCTIONS = {"nosys", "enosys"}


def syscall_name(function):
    # makesyscalls.sh names a "sys_" function after the rest, as syscall.h does with SYS_close.
    return function[len("sys_"):] if function.startswith("sys_") else function


def constant_name(name):
    # C++ reserves identifiers containing a double underscore, so __mac_syscall becomes MACOS_SYS_mac_syscall.
    return "MACOS_SYS_" + name.lstrip("_")


def parse_syscalls(path):
    names = {}
    with open(path, encoding="utf-8") as master:
        for line in master:
            entry = ENTRY.match(line)
            if not entry:
                continue

            function = FUNCTION_NAME.search(entry.group(2))
            if not function:
                sys.exit(f"no function name in syscalls.master line: {line.strip()}")

            number = int(entry.group(1))
            name = function.group(1)

            # Conditional blocks define a number once per branch; the first branch is the configuration macOS ships.
            if name not in UNUSED_FUNCTIONS and number not in names:
                names[number] = syscall_name(name)

    return names


def emit(names, xnu_version):
    table_size = max(names) + 1

    out = []
    out.append(f"// GENERATED by tools/macos-syscall-generator/generate.py from bsd/kern/syscalls.master of {xnu_version}")
    out.append("// -- do not edit by hand.")
    out.append("#pragma once")
    out.append("")
    out.append("#include <array>")
    out.append("#include <cstdint>")
    out.append("#include <string_view>")
    out.append("")
    out.append("namespace sogen")
    out.append("{")
    for number in sorted(names):
        out.append(f"    constexpr uint64_t {constant_name(names[number])} = {number};")
    out.append("")
    out.append(f"    constexpr std::array<std::string_view, {table_size}> MACOS_UNIX_SYSCALL_NAMES{{")
    for number in range(table_size):
        out.append(f'        "{names.get(number, "")}", // {number}')
    out.append("    };")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--syscalls-master", required=True)
    parser.add_argument("--xnu-version", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    names = parse_syscalls(args.syscalls_master)
    if not names:
        sys.exit("no syscalls found in syscalls.master")

    constants = [constant_name(name) for name in names.values()]
    duplicates = sorted({constant for constant in constants if constants.count(constant) > 1})
    if duplicates:
        sys.exit(f"syscalls share a constant name: {', '.join(duplicates)}")

    with open(args.output, "w", encoding="utf-8", newline="\n") as output:
        output.write(emit(names, args.xnu_version))


if __name__ == "__main__":
    main()
