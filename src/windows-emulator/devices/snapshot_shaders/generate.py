# Compiles the shaders snapshots use into snapshot_shaders.hpp. Needs glslc from the Vulkan SDK; run it after changing a
# shader: python generate.py
import os
import pathlib
import subprocess
import tempfile

directory = pathlib.Path(__file__).parent
glslc = pathlib.Path(os.environ.get("VULKAN_SDK", "")) / "Bin" / "glslc"

shaders = [
    ("read_samples_float", "comp", "read_samples.comp.glsl", ["FLOAT_FORMAT"]),
    ("read_samples_uint", "comp", "read_samples.comp.glsl", ["UINT_FORMAT"]),
    ("read_samples_sint", "comp", "read_samples.comp.glsl", ["SINT_FORMAT"]),
    ("fullscreen", "vert", "fullscreen.vert.glsl", []),
    ("write_sample_float", "frag", "write_sample.frag.glsl", ["FLOAT_FORMAT"]),
    ("write_sample_uint", "frag", "write_sample.frag.glsl", ["UINT_FORMAT"]),
    ("write_sample_sint", "frag", "write_sample.frag.glsl", ["SINT_FORMAT"]),
    ("write_sample_depth", "frag", "write_sample.frag.glsl", ["DEPTH_FORMAT"]),
    ("write_sample_stencil", "frag", "write_sample.frag.glsl", ["STENCIL_FORMAT"]),
]

lines = [
    "#pragma once",
    "",
    "// Generated by snapshot_shaders/generate.py from the GLSL next to it. Do not edit.",
    "",
    "#include <array>",
    "#include <cstdint>",
    "",
    "namespace sogen::snapshot_shaders",
    "{",
    "    // clang-format off",
]

with tempfile.TemporaryDirectory() as temporary:
    for name, stage, source, defines in shaders:
        output = pathlib.Path(temporary) / f"{name}.spv"
        command = [str(glslc), f"-fshader-stage={stage}", "-O", *[f"-D{define}" for define in defines], str(directory / source), "-o", str(output)]
        subprocess.run(command, check=True)
        data = output.read_bytes()
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        body = ", ".join(f"0x{word:08x}" for word in words)
        lines.append(f"    inline constexpr std::array<uint32_t, {len(words)}> {name}{{{body}}};")

lines += ["    // clang-format on", "}", ""]
(directory.parent / "snapshot_shaders.hpp").write_text("\n".join(lines), newline="\n")
